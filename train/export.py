#!/usr/bin/env python3
"""export.py - turn trained evaluator files into the C headers compiled into the browser engine.

usage: python3 train/export.py --best DIR [--out train/out]
  DIR/w8_std.bin, DIR/w8_noisy.bin   8-ball MLP weights (float32)
  DIR/snk_params.txt                  snooker evaluator parameters
  DIR/snk_table.bin                   snooker win table
  DIR/snk_use_table                   (optional) file containing 1 if the win-table evaluator won its arena
Writes std_weights.h, noisy_weights.h and snk_eval.h. Run ./build.sh afterwards.
"""
import argparse, os, struct, datetime

def floats(path):
    data = open(path, 'rb').read()
    return struct.unpack('<%df' % (len(data) // 4), data)

def write_weights(path, name, w, note):
    with open(path, 'w') as f:
        f.write('// generated by train/export.py (%s): %s\n' % (datetime.date.today(), note))
        f.write('static const float %s[%d] = {\n' % (name, len(w)))
        for i in range(0, len(w), 8):
            f.write(' '.join('%.7gf,' % x for x in w[i:i + 8]) + '\n')
        f.write('};\n')

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--best', required=True)
    ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), 'out'))
    a = ap.parse_args()
    for kind, name in (('std', 'NN_STD'), ('noisy', 'NN_NOISY')):
        p = os.path.join(a.best, 'w8_%s.bin' % kind)
        if os.path.exists(p):
            write_weights(os.path.join(a.out, '%s_weights.h' % kind), name, floats(p), p)
            print('wrote %s_weights.h' % kind)
    params = os.path.join(a.best, 'snk_params.txt')
    table = os.path.join(a.best, 'snk_table.bin')
    if os.path.exists(params) and os.path.exists(table):
        pv = [float(x) for x in open(params).read().split()]
        raw = open(table, 'rb').read()
        d0, nd, nr = struct.unpack('<3i', raw[:12])
        t = raw[12:]
        use = 0
        up = os.path.join(a.best, 'snk_use_table')
        if os.path.exists(up):
            use = int(open(up).read().strip() or '0')
        with open(os.path.join(a.out, 'snk_eval.h'), 'w') as f:
            f.write('// generated by train/export.py (%s)\n' % datetime.date.today())
            f.write('// snooker evaluator: E = a0 + a1*e1*(v1+cont) + a2*e2 + a3*snookered + a4*bih; D_eff = D + eScale*E\n')
            f.write('#define SNK_USE_TABLE %d\n' % use)
            f.write('static const double SNK_PARAMS[6] = {%s};\n' % ', '.join('%.6f' % x for x in pv))
            f.write('static const int SNK_TD0 = %d, SNK_TND = %d, SNK_TNR = %d;\n' % (d0, nd, nr))
            f.write('static const unsigned char SNK_TABLE[%d] = {\n' % len(t))
            for i in range(0, len(t), 32):
                f.write(','.join(str(b) for b in t[i:i + 32]) + ',\n')
            f.write('};\n')
        print('wrote snk_eval.h (use table: %d)' % use)

if __name__ == '__main__':
    main()
